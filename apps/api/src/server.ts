const port = Number(process.env.PORT ?? 4000);
app.listen(port, () => console.log(`Kravient API listening on http://localhost:${port}`));
void sendDailyReminders().catch(error => console.error("Initial reminder check failed", error));
setInterval(() => { void sendDailyReminders().catch(error => console.error("Scheduled reminder check failed", error)); }, 24 * 60 * 60 * 1000);
