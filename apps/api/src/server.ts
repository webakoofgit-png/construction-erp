if (process.env.NODE_ENV === "production") {
  const missing = ["DATABASE_URL", "JWT_SECRET", "WEB_ORIGIN", "EMAIL_FROM"].filter(name => !process.env[name] || process.env[name]?.includes("replace-with"));
  if (missing.length) throw new Error(`Missing production configuration: ${missing.join(", ")}`);
}

const app = express();
const localWebOrigins = [process.env.WEB_ORIGIN ?? "http://localhost:5173", "http://localhost:4173", "http://localhost:4174"];
app.use(cors({ origin: localWebOrigins }));
app.use(express.json());
app.use("/api", healthRouter);
app.use("/api/auth", authRouter);
app.use("/api/projects", projectsRouter);
app.use("/api/boqs", boqsRouter);
app.use("/api/materials", materialsRouter);
app.use("/api/procurement", procurementRouter);
app.use("/api/workforce", workforceRouter);
app.use("/api/progress", progressRouter);
app.use("/api/finance", financeRouter);
